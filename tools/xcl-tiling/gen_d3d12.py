#!/usr/bin/env python3
"""Generates src/d3d12.rs: the plain-data D3D12/DXGI terms the vendored XCL files speak in.

The vendored desc.rs and texture.rs take these types from the `windows` crate; here they are
local structures with the SDK's own names and values (no COM: the GPU paths of texture.rs are
left out of this crate, see PATCHES-tiling.md). Values come from the Windows SDK headers of
`xwin splat` (XWIN_DIR, default ~/.local/share/xwin), so they cannot drift from the real ones.

    python3 tools/xcl-tiling/gen_d3d12.py
"""

import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
xwin = os.environ.get("XWIN_DIR", os.path.expanduser("~/.local/share/xwin"))
sdk = os.path.join(xwin, "sdk", "include")


def header(name):
    for part in ("um", "shared"):
        path = os.path.join(sdk, part, name)
        if os.path.isfile(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                return f.read()
    sys.exit(f"gen_d3d12: no {name} under {sdk}")


def enum_values(text, name):
    m = re.search(r"typedef\s+enum\s+" + name + r"\s*\{(.*?)\}", text, re.S)
    if not m:
        sys.exit(f"gen_d3d12: enum {name} not found")
    out = {}
    value = 0
    for line in m.group(1).split(","):
        line = re.sub(r"/\*.*?\*/", "", line, flags=re.S).strip()
        if not line or line.startswith("#"):
            continue
        kv = line.split("=")
        key = kv[0].strip()
        if len(kv) > 1:
            value = int(kv[1].strip(), 0)
        out[key] = value
        value += 1
    return out


def defines(text, names):
    out = {}
    for name in names:
        m = re.search(r"#define\s+" + name + r"\s+\(?\s*([0-9xXa-fA-F]+)", text)
        if not m:
            sys.exit(f"gen_d3d12: {name} not found")
        out[name] = int(m.group(1), 0)
    return out


